"""Capture independent Rust processor results and complete structured errors.

Runs examples/processor_reference.rs (feature `test-reference`) in a temporary
directory, then writes:
  tests/fixtures/processor_reference.json   reviewed Rust results
  tests/c/processor_reference.h             the same data as a C table, used by
                                            tests/c/test_processor_parity.c

Usage: python3 scripts/generate_processor_reference.py [--check]
"""

from __future__ import annotations

import argparse
import json
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FIXTURE = ROOT / "tests/fixtures/processor_reference.json"
TABLE = ROOT / "tests/c/processor_reference.h"
STAGES = {"conversion", "validation", "execution", "persistence", "callback"}


def c_string(text: str) -> str:
    """C string literal; non-ASCII and control bytes use octal escapes."""
    out = []
    for byte in text.encode("utf-8"):
        char = chr(byte)
        if char in '"\\':
            out.append("\\" + char)
        elif 0x20 <= byte < 0x7F and char != "?":  # '?' avoids trigraph warnings
            out.append(char)
        else:
            out.append(f"\\{byte:03o}")
    return '"' + "".join(out) + '"'


def table(rows: dict[str, dict]) -> str:
    entries = []
    for name, result in rows.items():
        if "ok" in result:
            text = result["ok"]
            entries.append(f"    {{{c_string(name)}, 1, {c_string(text)}, {len(text.encode())}, "
                           f"TF_STAGE_ADAPTER, 0, NULL, NULL, NULL}},")
        else:
            error = result["error"]
            if error["stage"] not in STAGES:
                raise ValueError(f"unexpected stage {error['stage']}")
            entries.append(
                f"    {{{c_string(name)}, 0, NULL, 0, TF_STAGE_{error['stage'].upper()}, {error['code']}, "
                f"{c_string(error['message'])}, {c_string(error['instruction'])}, {c_string(error['input'])}}},"
            )
    return (
        "/* Rust processor reference results.\n"
        " * Generated by scripts/generate_processor_reference.py; do not edit by hand. */\n"
        "#ifndef TEXTFORGE_PROCESSOR_REFERENCE_H\n#define TEXTFORGE_PROCESSOR_REFERENCE_H\n\n"
        "#include <stddef.h>\n#include \"textforge.h\"\n\n"
        "typedef struct {\n    const char *name;\n    int ok;\n    const char *text;\n    size_t length;\n"
        "    TfStage stage;\n    unsigned code;\n    const char *message;\n    const char *instruction;\n"
        "    const char *input;\n} ReferenceCase;\n\n"
        "static const ReferenceCase REFERENCE_CASES[] = {\n" + "\n".join(entries) + "\n};\n\n"
        "#endif\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory(prefix="textforge-processor-reference-") as directory:
        output = subprocess.check_output(
            ["cargo", "run", "--quiet", "--locked", "--features", "test-reference",
             "--example", "processor_reference", "--", directory],
            cwd=ROOT, text=True,
        )
    rows: dict[str, dict] = {}
    for line in output.splitlines():
        if not line.startswith("REF\t"):
            continue
        _, name, status, *fields = line.split("\t")
        if status == "ok":
            rows[name] = {"ok": bytes.fromhex(fields[0]).decode()}
        else:
            decoded = (bytes.fromhex(value).decode() for value in fields[2:])
            rows[name] = {"error": {"code": int(fields[0]), "stage": fields[1].lower(),
                                    **dict(zip(("message", "instruction", "input"), decoded, strict=True))}}
    revision = (ROOT / "vendor/CORE_REVISION").read_text(encoding="utf-8").strip()
    fixture = json.dumps({"core_revision": revision, "cases": rows}, ensure_ascii=False, indent=2) + "\n"
    for path, content in ((FIXTURE, fixture), (TABLE, table(rows))):
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                raise SystemExit(f"Processor reference changed ({path.relative_to(ROOT)}); review before regenerating")
        else:
            path.write_text(content, encoding="utf-8")
    print(f"{'Verified' if args.check else 'Generated'} {len(rows)} independent processor reference cases")


if __name__ == "__main__":
    main()
