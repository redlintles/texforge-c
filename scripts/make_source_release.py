"""Create the reproducible, offline-buildable source release used by Conan and vcpkg.

The archive `dist/textforge-c-<version>.tar.gz` contains:
  * the committed sources of HEAD (`git archive`), without packaging/ and .github/
    (recipes describe the archive, so they cannot be part of it);
  * every crate of Cargo.lock vendored under vendor/crates (`cargo vendor`);
  * .cargo/config.toml redirecting crates.io to vendor/crates, so `cargo build
    --offline` (CMake option TEXTFORGE_C_OFFLINE, on by default for this tree)
    needs no network access.

Entries are sorted, owned by 0:0 and stamped with the time of the last commit
that changed archived content, and gzip carries no timestamp, so the same sources
always yield the same SHA-256/512 (also after committing updated recipes).

With --update-recipes, packaging/conan and packaging/vcpkg are rewritten for
this version, URL (packaging/source.json) and hashes.

Usage: python3 scripts/make_source_release.py [--allow-dirty] [--update-recipes]
"""

from __future__ import annotations

import argparse
import gzip
import hashlib
import io
import json
import re
import subprocess
import sys
import tarfile
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EXCLUDED = ("packaging/", ".github/")
CARGO_CONFIG = """# Generated by scripts/make_source_release.py: build from vendored crates only.
[source.crates-io]
replace-with = "vendored-sources"

[source.vendored-sources]
directory = "vendor/crates"
"""


def git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=ROOT, check=True, capture_output=True, text=True).stdout


def version() -> str:
    return re.search(r'^version = "([^"]+)"', (ROOT / "Cargo.toml").read_text(), re.M)[1]


def build_archive(output: Path, allow_dirty: bool) -> None:
    if git("status", "--porcelain") and not allow_dirty:
        raise SystemExit("Working tree has uncommitted changes; commit them or pass --allow-dirty")
    prefix = f"textforge-c-{version()}"
    # Stamp entries with the last commit that changed archived content, so committing
    # updated recipes (excluded from the archive) does not change the archive hash.
    excludes = [f":(exclude){path.rstrip('/')}" for path in EXCLUDED]
    epoch = int(git("log", "-1", "--format=%ct", "--", ".", *excludes).strip())
    with tempfile.TemporaryDirectory(prefix="textforge-c-release-") as scratch:
        tree = Path(scratch) / prefix
        tree.mkdir()
        archive = subprocess.run(["git", "archive", "--format=tar", "HEAD"], cwd=ROOT, check=True,
                                 capture_output=True).stdout
        with tarfile.open(fileobj=io.BytesIO(archive)) as source:
            members = [m for m in source.getmembers() if not m.name.startswith(EXCLUDED)]
            source.extractall(tree, members=members, filter="data")
        if allow_dirty:  # overlay the working tree for local testing
            for relative in git("ls-files", "-co", "--exclude-standard").splitlines():
                path = ROOT / relative
                if path.is_file() and not relative.startswith(EXCLUDED):
                    (tree / relative).parent.mkdir(parents=True, exist_ok=True)
                    (tree / relative).write_bytes(path.read_bytes())
        subprocess.run(["cargo", "vendor", "--locked", "--versioned-dirs", "--quiet", "vendor/crates"],
                       cwd=tree, check=True, stdout=subprocess.DEVNULL)
        (tree / ".cargo").mkdir()
        (tree / ".cargo/config.toml").write_text(CARGO_CONFIG)

        def normalize(info: tarfile.TarInfo) -> tarfile.TarInfo:
            info.uid = info.gid = 0
            info.uname = info.gname = ""
            info.mtime = epoch
            info.mode = 0o755 if info.isdir() or info.mode & 0o111 else 0o644
            return info

        output.parent.mkdir(parents=True, exist_ok=True)
        with open(output, "wb") as raw, gzip.GzipFile(filename="", mode="wb", fileobj=raw, mtime=0) as packed, \
                tarfile.open(fileobj=packed, mode="w", format=tarfile.PAX_FORMAT) as tar:
            for path in sorted(tree.parent.rglob("*")):
                tar.add(path, arcname=str(path.relative_to(tree.parent)), recursive=False, filter=normalize)


def digest(path: Path, algorithm: str) -> str:
    return hashlib.new(algorithm, path.read_bytes()).hexdigest()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--allow-dirty", action="store_true", help="include uncommitted changes (testing only)")
    parser.add_argument("--update-recipes", action="store_true", help="rewrite packaging/ for this archive")
    parser.add_argument("--output", type=Path, default=ROOT / "dist")
    args = parser.parse_args()
    output = args.output / f"textforge-c-{version()}.tar.gz"
    build_archive(output, args.allow_dirty)
    sha256, sha512 = digest(output, "sha256"), digest(output, "sha512")
    (output.parent / (output.name + ".sha256")).write_text(f"{sha256}  {output.name}\n")
    (output.parent / (output.name + ".sha512")).write_text(f"{sha512}  {output.name}\n")
    print(f"{output} ({output.stat().st_size // 1024} KiB)\nsha256 {sha256}\nsha512 {sha512}")
    if args.update_recipes:
        subprocess.run([sys.executable, str(ROOT / "scripts/update_recipes.py"), "--sha256", sha256,
                        "--sha512", sha512], check=True)


if __name__ == "__main__":
    main()
